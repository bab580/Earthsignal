  function text(key) {
    return (
      (languages[language] && languages[language][key]) ||
      (liveTranslations[language] && liveTranslations[language][key]) ||
      (chatUiTranslations[language] && chatUiTranslations[language][key]) ||
      (liveTranslations.en && liveTranslations.en[key]) ||
      languages.en[key] ||
      key
    );
  }

  function format(key, values = {}) {
    return text(key).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
  }

  function applyLanguage() {
    document.documentElement.lang = language;
    document.querySelectorAll("[data-i18n]").forEach(element => {
      const value = text(element.dataset.i18n);
      if (value) element.textContent = value;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
      const value = text(element.dataset.i18nPlaceholder);
      if (value) element.placeholder = value;
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach(element => {
      element.setAttribute("aria-label", text(element.dataset.i18nAriaLabel));
    });
  }

  function addChatMessage(message, kind) {
    const row = document.createElement("div");
    row.className = `chat-message-row chat-${kind}-row`;
    if (kind === "assistant") {
      const avatar = document.createElement("span");
      avatar.className = "chat-message-avatar";
      avatar.setAttribute("aria-hidden", "true");
      avatar.textContent = "E";
      row.append(avatar);
    }

    const item = document.createElement("p");
    item.className = `farmer-chat-message chat-${kind}`;
    item.textContent = message;
    row.append(item);
    document.getElementById("farmer-chat-messages").append(row);
    row.scrollIntoView({ block: "nearest" });
  }

  function answerTopic(topic, question) {
    if (question) addChatMessage(question, "user");
    addChatMessage(text(topicAnswers[topic] || "chatFallback"), "assistant");
  }

  function topicForQuestion(question) {
    const normalized = question.toLocaleLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    for (const [topic, words] of Object.entries(categories)) {
      if (words.some(word => normalized.includes(word))) return topic;
    }
    return null;
  }

  function setSmsStatus(message, isError = false) {
    const status = document.getElementById("farmer-sms-status");
    status.textContent = message;
    status.classList.toggle("error", isError);
  }

  async function postJson(path, payload) {
    const response = await fetch(earthSignalApiUrl(path), {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload)
    });
    const result = await response.json();
    if (!response.ok) throw new Error(result.detail || "The request could not be completed.");
    return result;
  }

